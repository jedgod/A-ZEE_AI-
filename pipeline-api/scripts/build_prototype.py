"""Regenerates prototype.py: a one-file launcher that embeds every app/*.py module.

Run from pipeline-api/:  python scripts/build_prototype.py
tests/test_prototype.py fails if prototype.py is out of date.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TEMPLATE = '''"""Standalone pipeline launcher (generated by scripts/build_prototype.py; do not edit).

Embeds the same app/ modules as the full project and launches the same wired API.
Install requirements.txt and the spaCy model, configure .env, and point DATABASE_URL at
PostgreSQL 18 with pgvector. It is not a fake in-memory backend.
"""
import os
import sys
import tempfile
from pathlib import Path

SOURCES = {
%s
}

if __name__ == "__main__":
    import uvicorn

    with tempfile.TemporaryDirectory(prefix="pipeline-") as directory:
        root = Path(directory)
        for name, content in SOURCES.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        sys.path.insert(0, str(root))
        # The working directory stays unchanged so .env remains discoverable.
        uvicorn.run("app.main:app", host="127.0.0.1", port=int(os.environ.get("PORT", "8000")))
'''


def sources() -> dict[str, str]:
    return {
        path.relative_to(ROOT).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted((ROOT / "app").glob("*.py"))
    }


def render() -> str:
    entries = "\n".join(f"    {name!r}: {content!r}," for name, content in sources().items())
    return TEMPLATE % entries


if __name__ == "__main__":
    (ROOT / "prototype.py").write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote prototype.py with {len(sources())} modules")
